# 2.3 Fungsi Pembersihan & Normalisasi Terpadu
def clean_and_normalize(text):
    if not isinstance(text, str):
        return ""

    # 1. Case Folding
    text = text.lower()

    # 2. Hapus URL
    text = re.sub(r'https?://\S+|www\.\S+', ' ', text)

    # 3. Hapus Mention (@username) dan Tagar (#hashtag)
    text = re.sub(r'@[A-Za-z0-9_]+', ' ', text)
    text = re.sub(r'#\w+', ' ', text)

    # 4. Hapus Karakter Non-Alphanumeric (Tanda baca diubah menjadi spasi)
    text = re.sub(r'[^a-zA-Z0-9\s]', ' ', text)

    # 5. Tokenisasi & Penggantian Kata Berbasis Kamus
    tokens = text.split()
    normalized_tokens = []
    for t in tokens:
        # Cek slang Indonesia dulu
        if t in slang_indo:
            t = slang_indo[t]
        # Cek kamus normalisasi bahasa Bali
        elif t in bali_normalization:
            t = bali_normalization[t]
        # Tangani sufiks kepemilikan bahasa Bali '-ne' (misal: solusine -> solusinya)
        elif t.endswith('ne') and len(t) > 4:
            base = t[:-2]
            if base in ['solusi', 'sampah', 'alat', 'gubernur', 'kebijakan', 'pejabat', 'masyarakat', 'bapak', 'truk', 'program', 'kantor']:
                t = base + 'nya'
            elif base in bali_normalization:
                t = bali_normalization[base] + 'nya'
        normalized_tokens.append(t)

    # 6. Normalisasi Spasi Berlebih
    return ' '.join(normalized_tokens).strip()

