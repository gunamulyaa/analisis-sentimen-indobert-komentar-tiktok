def detect_sentiment_inset(text):
    tokens = text.split()
    pos_score = 0
    neg_score = 0
    i = 0

    while i < len(tokens):
        word = tokens[i]
        # Pengecekan Negasi (Membalik polaritas kata berikutnya)
        if word in negation_words and (i + 1) < len(tokens):
            next_word = tokens[i + 1]
            if next_word in positive_words:
                neg_score += 1.5
                i += 2
                continue
            elif next_word in negative_words:
                pos_score += 1.5
                i += 2
                continue

        if word in positive_words:
            pos_score += 1.0
        elif word in negative_words:
            neg_score += 1.0
        i += 1

    if pos_score > neg_score:
        return "Positif"
    elif neg_score > pos_score:
        return "Negatif"
    else:
        return "Netral"

